// Лабораторная работа №1, часть 1. Вариант 13.
// Сравнить скорость сходимости (число слагаемых для достижения точности
// 10^-2, 10^-4, 10^-6) разложения числа пи:
// пи = sqrt(6 * (1 + 1/2^2 + 1/3^2 + 1/4^2 + ...))
// Задача решена циклом с постусловием (do-while): первое слагаемое нужно
// сложить в любом случае, а точность проверяется после каждого слагаемого.
// Точное значение пи в расчетах не используется, оно выводится
// только в конце для проверки.
#include <iostream>
#include <iomanip>
#include <windows.h>
#define _USE_MATH_DEFINES // Необходимо, чтобы использовать константу M_PI
#include <math.h>
using namespace std;

int main()
{
    SetConsoleOutputCP(CP_UTF8);
    setlocale(LC_ALL,"RU");

    setlocale(LC_ALL, "Russian"); // Чтобы в консоли выводились русские буквы
    double e;
    cout << "Точность = "; // Например, 0.01, 0.0001, 0.000001
    cin >> e;

    double sum = 0; // Сумма ряда в скобках
    double sl;      // Очередное слагаемое 1/k^2
    int k = 1;      // Номер слагаемого
    do
    {
        sl = 1. / (k * k); // Очередное слагаемое
        sum += sl;         // Считаем сумму
        k++;
    } while (sl >= e); // Пока слагаемое >= точности цикл продолжается

    cout << fixed << setprecision(10);
    cout << "пи = " << sqrt(6 * sum) << ", слагаемых " << k - 1 << endl;
    cout << "Точное значение: пи = " << M_PI << endl;
    return 0;
}